        // ===== EMAIL TASDIQLASH KODI =====
        // Kod haqiqiy pochtaga yuborilishi uchun https://www.emailjs.com da bepul akkaunt oching
        // va quyidagi 3 qiymatni to'ldiring. Bo'sh qolsa — TEST REJIMI (kod ekranda ko'rsatiladi).
        const EMAIL_CONFIG = { serviceId: 'service_ck5z5f6', templateId: 'template_v045sef', publicKey: 'L6ugd2WcQeA0Qv-FZ' };
        const CODE_TTL_MS = 10 * 60 * 1000, CODE_COOLDOWN_S = 60, CODE_MAX_TRIES = 5;
        let authCode = null;          // { email, codes[], expires, tries }
        let codeCooldownTimer = null;
        let lastMailError = '';

        function resetAuthCode() {
            authCode = null;
            clearInterval(codeCooldownTimer);
            const wrap = document.getElementById('auth-code-wrap');
            if (!wrap) return;
            wrap.classList.add('hidden');
            const inp = document.getElementById('auth-code'); inp.value = ''; inp.required = false;
            document.getElementById('auth-code-hint').textContent = '';
            const btn = document.getElementById('auth-send-code-btn'); btn.disabled = false; btn.textContent = 'Kod yuborish';
        }
        function onAuthEmailInput() {
            const v = document.getElementById('auth-email').value.trim().toLowerCase();
            if (authCode && authCode.email !== v) resetAuthCode();
        }
        function startCodeCooldown() {
            const btn = document.getElementById('auth-send-code-btn');
            let sec = CODE_COOLDOWN_S;
            clearInterval(codeCooldownTimer);
            const tick = () => {
                if (sec <= 0) { clearInterval(codeCooldownTimer); btn.disabled = false; btn.textContent = 'Qayta yuborish'; return; }
                btn.disabled = true; btn.textContent = `Qayta yuborish (${sec} s)`; sec--;
            };
            tick(); codeCooldownTimer = setInterval(tick, 1000);
        }
        async function deliverAuthCode(email, name, code) {
            const c = EMAIL_CONFIG;
            if (!c.serviceId || !c.templateId || !c.publicKey) return 'test';
            try {
                const r = await fetch('https://api.emailjs.com/api/v1.0/email/send', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({
                        service_id: c.serviceId, template_id: c.templateId, user_id: c.publicKey,
                        template_params: {
                            to_email: email, user_name: name, app_name: 'EduFlow', minutes: 10,
                            code: code, passcode: code,
                            time: (() => { const d = new Date(Date.now() + CODE_TTL_MS), z = n => String(n).padStart(2, '0'); return `${z(d.getDate())}.${z(d.getMonth() + 1)}.${d.getFullYear()} ${z(d.getHours())}:${z(d.getMinutes())}`; })()
                        }
                    })
                });
                if (r.ok) return 'sent';
                lastMailError = `${r.status} ${(await r.text()).slice(0, 160)}`.trim();
                console.error('EmailJS xatosi:', lastMailError);
                return 'failed';
            } catch (err) { lastMailError = String(err && err.message || err).slice(0, 160); console.error('EmailJS xatosi:', err); return 'failed'; }
        }
        async function sendAuthCode() {
            const emailEl = document.getElementById('auth-email');
            const email = emailEl.value.trim();
            if (!/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)) { alert("Email manzilini to'g'ri kiriting."); emailEl.focus(); return; }
            const key = email.toLowerCase();
            const existing = getUsers().find(u => !u.deleted && (u.email || '').toLowerCase() === key);
            if (authMode === 'register' && existing) { alert("Bu email bilan akkaunt allaqachon mavjud. Iltimos, tizimga kiring."); return; }
            if (authMode === 'login' && !existing) { alert("Bunday akkaunt topilmadi. Avval \"Akkaunt yaratish\" tugmasi orqali ro'yxatdan o'ting."); return; }
            const btn = document.getElementById('auth-send-code-btn');
            btn.disabled = true;
            const code = String(crypto.getRandomValues(new Uint32Array(1))[0] % 900000 + 100000);
            const name = authMode === 'register' ? document.getElementById('auth-name').value.trim() : existing.name;
            const status = await deliverAuthCode(email, name, code);
            if (status === 'failed') { alert("Kod yuborilmadi. Birozdan so'ng qayta urinib ko'ring." + (lastMailError ? ` (${lastMailError})` : '')); btn.disabled = false; return; }
            const same = authCode && authCode.email === key && Date.now() < authCode.expires;
            authCode = { email: key, codes: [code, ...(same ? authCode.codes : [])].slice(0, 3), expires: Date.now() + CODE_TTL_MS, tries: same ? authCode.tries : 0 };
            document.getElementById('auth-code-wrap').classList.remove('hidden');
            const inp = document.getElementById('auth-code'); inp.value = ''; inp.required = true; inp.focus();
            document.getElementById('auth-code-hint').textContent = status === 'sent'
                ? `Kod ${email} manziliga yuborildi. 10 daqiqa amal qiladi.`
                : `Test rejimi: email xizmati ulanmagan. Kod: ${code}`;
            startCodeCooldown();
        }

        function handleAuthSubmit(e) {
            e.preventDefault();
            const email = document.getElementById('auth-email').value.trim();
            const key = email.toLowerCase();
            const existing = getUsers().find(u => !u.deleted && (u.email || '').toLowerCase() === key);

            if (!authCode || authCode.email !== key) { alert("Avval emailga kod yuboring."); return; }
            if (Date.now() > authCode.expires) { resetAuthCode(); alert("Kod muddati tugadi. Yangi kod so'rang."); return; }
            if (!authCode.codes.includes(document.getElementById('auth-code').value.replace(/\D/g, ''))) {
                authCode.tries++;
                if (authCode.tries >= CODE_MAX_TRIES) { resetAuthCode(); alert("Urinishlar soni tugadi. Yangi kod so'rang."); }
                else alert("Kod noto'g'ri. Qaytadan urinib ko'ring.");
                return;
            }
            resetAuthCode();

            if (authMode === 'register') {
                if (existing) { alert("Bu email bilan akkaunt allaqachon mavjud. Iltimos, tizimga kiring."); return; }
                const name = document.getElementById('auth-name').value.trim();
                currentUser = { name, email, avatar: `https://picsum.photos/seed/${name}/100/100`, isPro: false, isAdmin: false };
            } else {
                if (!existing) { alert("Bunday akkaunt topilmadi. Avval \"Akkaunt yaratish\" tugmasi orqali ro'yxatdan o'ting."); return; }
                currentUser = {
                    name: existing.name,
                    email: existing.email,
                    avatar: `https://picsum.photos/seed/${existing.name}/100/100`,
                    isPro: isProActive(existing),
                    isAdmin: false,
                    ...(existing.proUntil ? { proPlan: existing.proPlan || 'monthly', proUntil: existing.proUntil } : {})
                };
            }
            localStorage.setItem('eduflow_current_user', JSON.stringify(currentUser));
            registerUserInRegistry(currentUser);
            updateHeaderAuthUI();
            closeAuthModal();
            navigateTo('home');
        }

