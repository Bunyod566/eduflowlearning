        function parseCourseVideo(url) {
            if (!url) return null;
            let u;
            try { u = new URL(String(url).trim()); } catch (e) { return null; }
            if (!/^https?:$/.test(u.protocol)) return null;
            const h = u.hostname.replace(/^www\./, '');
            let id = null;
            if (h === 'youtu.be') id = u.pathname.slice(1);
            else if (h.endsWith('youtube.com')) {
                if (u.pathname === '/watch') id = u.searchParams.get('v');
                else { const m = u.pathname.match(/^\/(embed|shorts|live)\/([\w-]+)/); if (m) id = m[2]; }
            }
            if (id && /^[\w-]{6,15}$/.test(id)) return { type: 'youtube', src: 'https://www.youtube.com/embed/' + id };
            if (/\.(mp4|webm|ogg|mov)$/i.test(u.pathname)) return { type: 'file', src: u.href };
            return { type: 'link', src: u.href };
        }

