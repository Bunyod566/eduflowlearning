        function cloudUpsertUser(user, registeredAt) {
            if (!cloudDb) return;
            // Hujjat ID si birinchi ro'yxatdan o'tgan emaildan olinadi va o'zgarmaydi
            if (!user.cloudId) {
                user.cloudId = encodeURIComponent(user.email.trim().toLowerCase());
                if (currentUser && currentUser.email === user.email) {
                    localStorage.setItem('eduflow_current_user', JSON.stringify(user));
                }
            }
            const ref = cloudDb.collection('users').doc(user.cloudId);
            const data = { name: user.name, email: user.email.trim(), isPro: !!user.isPro };
            if (user.proUntil) { data.proPlan = user.proPlan || 'monthly'; data.proUntil = user.proUntil; }
            ref.get().then(doc => {
                if (doc.exists) {
                    const d = doc.data();
                    if (d.deleted) return; // o'chirilgan akkaunt
                    if (d.name === data.name && d.email === data.email && !!d.isPro === data.isPro && (!data.proUntil || d.proUntil === data.proUntil)) return; // o'zgarish yo'q
                } else {
                    data.registeredAt = registeredAt || new Date().toISOString();
                }
                return ref.set(data, { merge: true });
            }).catch(err => { console.error('Firestore yozish xatosi:', err); cloudState = 'error'; });
        }

        function registerUserInRegistry(user, oldEmail) {
            if (!user || user.isAdmin || !user.email) return;
            const list = getUsers();
            const lookup = (oldEmail || user.email).trim().toLowerCase();
            const i = list.findIndex(u => (u.email || '').toLowerCase() === lookup);
            let registeredAt, dirty = false;
            if (i === -1) {
                registeredAt = new Date().toISOString();
                list.push({ name: user.name, email: user.email.trim(), registeredAt, isPro: !!user.isPro, ...(user.proUntil ? { proPlan: user.proPlan || 'monthly', proUntil: user.proUntil } : {}) });
                dirty = true;
            } else {
                registeredAt = list[i].registeredAt;
                if (list[i].name !== user.name || list[i].email !== user.email.trim() || !!list[i].isPro !== !!user.isPro || (user.proUntil && list[i].proUntil !== user.proUntil)) {
                    list[i].name = user.name;
                    list[i].email = user.email.trim();
                    list[i].isPro = !!user.isPro;
                    if (user.proUntil) { list[i].proPlan = user.proPlan || 'monthly'; list[i].proUntil = user.proUntil; }
                    dirty = true;
                }
            }
            if (dirty) saveUsers(list);
            cloudUpsertUser(user, registeredAt);
        }

